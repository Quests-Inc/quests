// Coverage of the supplied CyrillicGothSHA face; unsupported symbols use DejaVu.
func gothicHasRune(ch rune) bool {
	for _, span := range [][2]rune{{0, 0}, {29, 29}, {32, 126}, {128, 129}, {141, 144}, {157, 158}, {160, 255}, {338, 339}, {352, 353}, {376, 376}, {402, 402}, {700, 700}, {710, 710}, {732, 732}, {1025, 1025}, {1028, 1028}, {1030, 1031}, {1038, 1038}, {1040, 1103}, {1105, 1105}, {1108, 1108}, {1110, 1111}, {1118, 1118}, {1168, 1169}, {1252, 1253}, {8211, 8212}, {8216, 8218}, {8220, 8222}, {8224, 8226}, {8230, 8230}, {8240, 8240}, {8249, 8250}, {8482, 8482}, {8729, 8729}} {
		if ch >= span[0] && ch <= span[1] {
			return true
		}
	}
	return false
}
